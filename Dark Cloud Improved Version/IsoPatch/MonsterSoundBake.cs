    /// <summary>The monster sound library: every monster sound program of the dungeon sound sets in one archive file, so a floor
    /// can load the sounds of the species on it wherever the randomizer put them (tools/stubs/monster_bank.s builds the floor's
    /// monster bank from it as the floor loads).
    ///
    /// A monster sound id (601–2596) resolves through the ELF's static se_info table to a (program, note) of the monster bank —
    /// the `*_g` bank of the dungeon's sound set (`sound\set\snd{100 + dungeon}.snd`), on MIDI port 10. Each set's bank holds only
    /// its own natives' sounds, so a species placed elsewhere played nothing. A (program, note) is the same sound in every set
    /// that has it (all 170 shared ones match). A program carries up to three species' sounds, each on its own 30-note window,
    /// and each set only its natives' windows, so the library's unit is (program, window) — program × 4 + window — gathered across
    /// the eleven dungeon sets (<see cref="Gather"/>).
    ///
    /// The file (little-endian), its front read whole by the cave:
    ///   +0x0000 'DCMS', version 2, front bytes, front sectors
    ///   +0x0010 512 × 16 B by unit: front offset of its records (0 = absent), first sector and bytes (whole sectors) of its
    ///           samples, then split / sample-set / sample / VAG counts
    ///   +0x2010 176 × 2 units by species-table index (0xFFFF = none; <see cref="SpeciesUnits"/>)
    ///   +0x22D0 16 × 4 units by dungeon map (selectMapNo): units its own bank sounds that no species owns (0xFFFF = none) — sounds
    ///           the dungeon plays through its basic tables, kept in its floors' banks
    ///   +0x2350 176 × 8 B by species-table index: first sector and bytes of its Steve lines (0 bytes = none; <see cref="SteveBlocks"/>)
    ///   +0x28D0 each unit's records, 16-aligned: the program's 36-byte header and the unit's 20-byte splits, 6-byte sample sets,
    ///           42-byte samples and 8-byte VAG entries, indexed from 0 within the unit and the VAG offsets from its samples' start
