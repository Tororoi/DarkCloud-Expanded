        private sealed class Bank
        {
            internal byte[] Hd, Bd;
            internal int ProgOff, SsetOff, SmplOff, VagiOff;
            internal uint[] Prog, Sset, Smpl, Vagi;
            internal int[] VagStarts;
        }

        private static uint[] Table(byte[] hd, int off) =>
            Enumerable.Range(0, (int)U32(hd, off + 12) + 1).Select(i => U32(hd, off + 16 + i * 4)).ToArray();

        private static Bank ReadBank(byte[] hd, byte[] bd)
        {
            var b = new Bank { Hd = hd, Bd = bd };
            b.ProgOff = (int)U32(hd, 0x24); b.SsetOff = (int)U32(hd, 0x28); b.SmplOff = (int)U32(hd, 0x2C); b.VagiOff = (int)U32(hd, 0x30);
            b.Prog = Table(hd, b.ProgOff); b.Sset = Table(hd, b.SsetOff); b.Smpl = Table(hd, b.SmplOff); b.Vagi = Table(hd, b.VagiOff);
            b.VagStarts = b.Vagi.Where(o => o != uint.MaxValue).Select(o => (int)U32(hd, b.VagiOff + (int)o)).Distinct().OrderBy(a => a).ToArray();
            return b;
        }

        private static int VagSize(Bank b, int addr)
        {
            int i = Array.BinarySearch(b.VagStarts, addr);
            return (i + 1 < b.VagStarts.Length ? b.VagStarts[i + 1] : b.Bd.Length) - addr;
        }

        private static int Split(Bank b, int prog, int k) { int p = b.ProgOff + (int)b.Prog[prog]; return p + (int)U32(b.Hd, p) + k * b.Hd[p + 5]; }

        /// <summary>The 30-note window a split's first note falls in.</summary>
        private static int Window(byte lo) => lo < NoteFirst ? 0 : (lo - NoteFirst) / NoteWindow;

        /// <summary>One unit gathered across the sets — the union of every set's sounding splits of the program's window by note range,
        /// in note order and renumbered — with the program's header, its records indexed from 0 and its sample bytes (a sample several
        /// sets carry stored once). Null when no set sounds it.</summary>
        private static (byte[] records, byte[] samples, int nSplit, int nSset, int nSmpl, int nVagi)? Gather(List<Bank> banks, int prog, int window)
        {
            var chosen = new SortedDictionary<(byte lo, byte hi), (Bank bank, int at)>();
            byte[] header = null;
            foreach (var b in banks)
            {
                if (prog >= b.Prog.Length || b.Prog[prog] == uint.MaxValue) continue;
                int rec = b.ProgOff + (int)b.Prog[prog];
                if (U32(b.Hd, rec) != ProgHeader || b.Hd[rec + 5] != SplitBytes) throw new IOException($"program {prog}: unexpected record layout");
                header ??= b.Hd.AsSpan(rec, ProgHeader).ToArray();
                for (int k = 0; k < b.Hd[rec + 4]; k++)
                {
                    int at = Split(b, prog, k);
                    var key = (b.Hd[at + 2], b.Hd[at + 4]);
                    if (U16(b.Hd, at) != None && Window(b.Hd[at + 2]) == window && !chosen.ContainsKey(key)) chosen[key] = (b, at);
                }
            }
            if (chosen.Count == 0) return null;
            if (chosen.Count > 255) throw new IOException($"program {prog}: {chosen.Count} splits");
            var splits = new List<byte[]>(); var ssets = new List<byte[]>(); var smpls = new List<byte[]>(); var vagis = new List<byte[]>();
            var samples = new MemoryStream();
            var vagIndex = new Dictionary<string, int>();                      // a sample several sets carry is stored once (by its bytes)
            foreach (var (src, at) in chosen.Values)
            {
                byte[] split = src.Hd.AsSpan(at, SplitBytes).ToArray();
                byte[] ss = src.Hd.AsSpan(src.SsetOff + (int)src.Sset[U16(split, 0)], SsetBytes).ToArray();
                if (ss[3] != 1) throw new IOException($"program {prog}: a sample set of {ss[3]} samples");
                ushort smpl = U16(ss, 4);
                if (smpl != None)
                {
                    byte[] sm = src.Hd.AsSpan(src.SmplOff + (int)src.Smpl[smpl], SmplBytes).ToArray();
                    ushort vag = U16(sm, 0);
                    if (vag != None)
                    {
                        int addr = (int)U32(src.Hd, src.VagiOff + (int)src.Vagi[vag]);
                        byte[] va = src.Hd.AsSpan(src.VagiOff + (int)src.Vagi[vag], VagiBytes).ToArray();
                        byte[] bytes = src.Bd.AsSpan(addr, VagSize(src, addr)).ToArray();
                        string key = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(bytes)) + Convert.ToHexString(va, 4, 4);
                        if (!vagIndex.TryGetValue(key, out int vi))
                        {
                            U32(va, 0, (uint)samples.Length);
                            samples.Write(bytes, 0, bytes.Length);
                            vi = vagis.Count; vagis.Add(va); vagIndex[key] = vi;
                        }
                        U16(sm, 0, (ushort)vi);
                    }
                    U16(ss, 4, (ushort)smpls.Count); smpls.Add(sm);
                }
                U16(split, 0, (ushort)ssets.Count); ssets.Add(ss);
                split[5] = (byte)splits.Count;
                splits.Add(split);
            }
            if (ssets.Count > 255 || smpls.Count > 255 || vagis.Count > 255) throw new IOException($"program {prog}: too many records");
            header[4] = (byte)splits.Count;
            var r = new MemoryStream();
            r.Write(header, 0, ProgHeader);
            foreach (var x in splits.Concat(ssets).Concat(smpls).Concat(vagis)) r.Write(x, 0, x.Length);
            return (r.ToArray(), samples.ToArray(), splits.Count, ssets.Count, smpls.Count, vagis.Count);
        }

        /// <summary>Whether <paramref name="b"/>'s own copy of the program sounds any note of the window.</summary>
        private static bool Sounds(Bank b, int prog, int window)
        {
            if (prog >= b.Prog.Length || b.Prog[prog] == uint.MaxValue) return false;
            int rec = b.ProgOff + (int)b.Prog[prog];
            for (int k = 0; k < b.Hd[rec + 4]; k++)
            {
                int at = Split(b, prog, k);
                if (U16(b.Hd, at) != None && Window(b.Hd[at + 2]) == window) return true;
            }
            return false;
        }

        /// <summary>Each species' Steve lines as a block (by species-table index): count, text halfwords, then (message id, the text's
        /// halfword offset in the block's text) a line, then the texts (each through its 0xFF01). A species' lines are messages
        /// 4000 + its name number × 10 + 0..9 of the dungeon Steve files that carry them (each file only its natives'); the
        /// extension species take their template's (Holy Gemron's) texts under their own ids.</summary>
        private static List<(int t, byte[] block)> SteveBlocks(Func<string, byte[]> read)
        {
            var files = SteveFiles.Select(n => read($@"dun\message\ww_mes\{n}.mes")).ToList();
            ushort[] Line(int id)                       // the first file whose entry for it has text (some carry an empty one at their text's end)
            {
                foreach (var f in files)
                {
                    int cnt = U16(f, 0), end = U16(f, 2);
                    for (int i = 0; i < cnt; i++)
                        if (U16(f, 4 + i * 4) == id && 2 * (cnt + U16(f, 6 + i * 4) + 1) < end) return MesTextBaker.MesExtract(f, id);
                }
                return null;
            }
            var blocks = new List<(int, byte[])>();
            foreach (var (t, own, source) in SteveSpecies())
            {
                var lines = Enumerable.Range(0, SteveLines).Select(k => (id: SteveFirst + own * SteveLines + k, words: Line(SteveFirst + source * SteveLines + k)))
                                      .Where(l => l.words != null).ToList();
                if (lines.Count == 0) continue;
                int words = lines.Sum(l => l.words.Length), head = 4 + lines.Count * 4;
                var b = new byte[head + words * 2];
                U16(b, 0, (ushort)lines.Count); U16(b, 2, (ushort)words);
                int at = 0;
                for (int k = 0; k < lines.Count; k++)
                {
                    U16(b, 4 + k * 4, (ushort)lines[k].id); U16(b, 6 + k * 4, (ushort)at);
                    foreach (ushort w in lines[k].words) { U16(b, head + at * 2, w); at++; }
                }
                if (b.Length > SteveBlockMax) throw new IOException($"species {t}: Steve lines of {b.Length:N0} B past {SteveBlockMax:N0}");
                blocks.Add((t, b));
            }
            return blocks;
        }

        /// <summary>Species-table index → (its name number, the name number whose Steve texts it takes).</summary>
        private static IEnumerable<(int t, int own, int source)> SteveSpecies()
        {
            foreach (var kv in EnemySpecies.All)
            {
                if (kv.Value.TableIndex is not int t || t >= SpeciesRows) continue;
                int own = kv.Value.Id, source = t >= EnemySpeciesTable.VanillaCount ? TemplateName(t) : own;
                yield return (t, own, source);
            }
        }

        /// <summary>The name number of the vanilla species an extension row is built on (SpeciesRows).</summary>
        private static int TemplateName(int t)
        {
            foreach (var (species, template, _, _, _) in Dark_Cloud_Improved_Version.SpeciesRows.Rows)
                if (species.TableIndex == t) return EnemySpecies.All[template].Id;
            return EnemySpecies.All[t].Id;
        }

        internal static byte[] Build(Func<string, byte[]> read)
        {
            var banks = new List<Bank>(); var setPrograms = new List<int[]>();
            for (int s = 0; s < Sets; s++)
            {
                var pack = ChrPack.Parse(read($@"sound\set\snd{FirstSet + s}.snd"));
                var g = pack.Records.First(r => r.Name.EndsWith("_g.hd", StringComparison.OrdinalIgnoreCase));
                var bank = ReadBank(g.Payload, pack.Require(g.Name.Substring(0, g.Name.Length - 2) + "bd").Payload);
                banks.Add(bank);
                setPrograms.Add(Enumerable.Range(0, bank.Prog.Length).Where(p => bank.Prog[p] != uint.MaxValue).ToArray());
            }
            var front = new MemoryStream(); front.Write(new byte[RecordsOff], 0, RecordsOff);
            var blocks = new List<(int unit, byte[] bytes)>();
            var dir = new byte[Units * 16];
            var present = new HashSet<int>();
            foreach (int prog in setPrograms.SelectMany(p => p).Distinct().OrderBy(p => p))
                for (int window = 0; window < Windows; window++)
                {
                    int unit = prog * 4 + window;
                    if (unit >= Units) throw new IOException($"program {prog} past the directory");
                    var gathered = Gather(banks, prog, window);
                    if (gathered == null) continue;
                    var (records, samples, nSplit, nSset, nSmpl, nVagi) = gathered.Value;
                    front.Position = Align16((int)front.Length); front.SetLength(front.Position);
                    U32(dir, unit * 16, (uint)front.Position);
                    front.Write(records, 0, records.Length);
                    dir[unit * 16 + 12] = (byte)nSplit; dir[unit * 16 + 13] = (byte)nSset; dir[unit * 16 + 14] = (byte)nSmpl; dir[unit * 16 + 15] = (byte)nVagi;
                    blocks.Add((unit, samples)); present.Add(unit);
                }
            byte[] head = front.ToArray();
            int frontBytes = head.Length, frontSectors = (int)(Align(frontBytes) / SectorBytes);
            var file = new MemoryStream(); file.Write(head, 0, head.Length); file.SetLength(Align(file.Length));
            foreach (var (unit, bytes) in blocks)
            {
                file.Position = file.Length;
                U32(dir, unit * 16 + 4, (uint)(file.Position / SectorBytes));
                U32(dir, unit * 16 + 8, (uint)Align(bytes.Length));
                file.Write(bytes, 0, bytes.Length); file.SetLength(Align(file.Length));
            }
            var steveDir = new byte[SpeciesRows * 8];
            var steveAt = new Dictionary<string, (uint sector, uint bytes)>();
            var steve = SteveBlocks(read);
            foreach (var (t, block) in steve)
            {
                string key = Convert.ToHexString(block);
                if (!steveAt.TryGetValue(key, out var at))
                {
                    file.Position = file.Length;
                    at = ((uint)(file.Position / SectorBytes), (uint)Align(block.Length));
                    file.Write(block, 0, block.Length); file.SetLength(Align(file.Length));
                    steveAt[key] = at;
                }
                U32(steveDir, t * 8, at.sector); U32(steveDir, t * 8 + 4, at.bytes);
            }
            byte[] o = file.ToArray();
            steveDir.CopyTo(o, SteveOff);
            System.Text.Encoding.ASCII.GetBytes("DCMS").CopyTo(o, 0);
            U32(o, 4, 2); U32(o, 8, (uint)frontBytes); U32(o, 12, (uint)frontSectors);
            dir.CopyTo(o, DirOff);
            for (int t = 0; t < SpeciesRows; t++)
                for (int c = 0; c < 2; c++) U16(o, SpeciesOff + t * 4 + c * 2, t < SpeciesUnits.GetLength(0) ? SpeciesUnits[t, c] : None);
            var owned = new HashSet<int>(Enumerable.Range(0, SpeciesUnits.GetLength(0)).SelectMany(t => new[] { (int)SpeciesUnits[t, 0], SpeciesUnits[t, 1] }));
            for (int m = 0; m < KeepRows; m++)
            {
                var keep = m < Sets
                    ? setPrograms[m].SelectMany(p => Enumerable.Range(0, Windows).Where(w => Sounds(banks[m], p, w)).Select(w => p * 4 + w))
                                    .Where(u => present.Contains(u) && !owned.Contains(u)).ToArray()
                    : Array.Empty<int>();
                if (keep.Length > KeepCells) throw new IOException($"dungeon map {m}: {keep.Length} kept units");
                for (int c = 0; c < KeepCells; c++) U16(o, KeepOff + m * KeepCells * 2 + c * 2, c < keep.Length ? (ushort)keep[c] : None);
            }
            return o;
        }

        internal static void Run(IsoArchive arc, Action<string> log)
        {
            if (!arc.Has(Library))
            {
                if (!arc.Has(Dead)) throw new IOException($"neither {Library} nor the dead entry {Dead} is in the archive");
                arc.Rename(Dead, Library);
            }
            byte[] lib = Build(arc.Read);
            arc.Redirect(Library, lib);
            log($"{Library}: {lib.Length:N0} B, front {U32(lib, 8):N0} B");
        }
